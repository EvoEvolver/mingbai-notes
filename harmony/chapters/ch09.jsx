    <Block id="ornament" toc="9-6 装饰音型" kicker="9-6 · 装饰音型" title="装饰音型：润色与炫技">
      <Narrate />
      <p>在基本织体之上，还有润色与装饰手法，常集中在前奏、高潮和华彩乐段（Cadenza）。以钢琴为例：</p>
      <ul>
        <li><b>快速跑动</b>：音阶、半音阶、琶音及其组合，<Play notes="C4 D4 E4 F4 G4 A4 B4 C5 D5 E5 F5 G5 A5 B5 C6" melodic gap={0.06}>听一串快速音阶</Play>。
          《野蜂飞舞》用快速半音绕圈模仿蜂鸣；肖邦《革命练习曲》左手汹涌下行、右手缓慢凝重——与戏曲的「紧拉慢唱」不谋而合。速度不是一切：机器能弹得更快，却没有人的弹性与情感。</li>
        <li><b>琶音与刮奏</b>：都是快速奏出一组音，区别在速度与密度：<Play notes="C3 E3 G3 C4 E4 G4 C5" melodic gap={0.09}>琶音</Play> 与 <Play notes="C4 D4 E4 F4 G4 A4 B4 C5 D5 E5 F5 G5 A5 B5 C6" melodic gap={0.025}>白键刮奏</Play>。
          钢琴无法真正连续滑音（Glissando 本义），只能用刮奏近似；德彪西《月光》第二部分下方流动的琶音像夜风与波光。</li>
        <li><b>快速交替</b>：倚音、波音、回音（装饰音），相差二度的<Play notes="D5 E5 D5 E5 D5 E5 D5 E5 D5 E5 D5 E5 D5" melodic gap={0.07}>颤音</Play>，同音重复或相隔更远的<Play notes="C3 C4 C3 C4 C3 C4 C3 C4 C3 C4 C3 C4" melodic gap={0.07}>震音</Play>，以及超过八度的<b>大跳</b>：
          李斯特《钟》用大跳模仿钟声，肖邦《雨滴前奏曲》的同音重复兼作属持续音，贝多芬《悲怆》第一乐章左手是八度震音。</li>
        <li><b>双音、八度与和弦</b>：<Play seq={["E4 C4", "F4 D4", "G4 E4", "A4 F4", "G4 E4"]} gap={0.3}>三度双音</Play>支持旋律，就像平行的伴唱；八度加强旋律、和声或低音；也可让双音中的一个音保持不动（持续音）。李斯特《鬼火》以无规律的变化双音著称。</li>
      </ul>
      <p>其他乐器也各有特技：弦乐的泛音、跳弓、拨奏、揉弦，吉他的轮指、扫弦、切音，管乐的双吐、三吐、花舌、循环换气……都是织体的有机组成。最好的练习，是给同一首作品编配几种不同织体的版本。</p>
    </Block>


      <p>分解的形式还有：短琶音、长琶音（超过八度）、波浪式（圣桑《天鹅》象征湖水）、阿尔贝蒂低音（纯净轻快，适合儿歌、乡村、民谣，但不宜太低）、理查十度（克莱德曼《童年的回忆》）、加入持续音（可以是和弦音或和弦外音，在低音或上方反复），
        以及加入大二度、大小六度的外音（适合「中国风」，如《青花瓷》钢琴改编），或快速跑动的分解（《长江之歌》的浪花、《十年》的钢琴弹唱）。和弦有四个音以上时，可交替出现或按第五章的规则省略次要音、旋律已有的音。</p>

    <Block id="rhythm" toc="9-5 节拍" kicker="9-5 · 从节拍到节奏型" title="节拍：均匀的拍 + 循环的强弱"
      lead="点不同拍子循环播放：柱高是逻辑强弱，强拍的「敲击」更高、更响。特别比较 3/4 与 6/8——小节一样长，律动却不同。">
      <Narrate />
      <RhythmLab />
      <p>节奏是音的长短与强弱形成的模式，可以说是音乐去掉音高后剩下的部分（芬兰民谣《伊娃的波尔卡》去掉音高，洗脑的节奏依然在）。它包括两个层面：<C id="meter">节拍</C>与节奏型。</p>
      <p><b>拍与速度</b>：拍更多是心理上的「脉冲」。速度用 bpm 精确表示，也用快板（Allegro，约 120–156 bpm，同时带有「欢快」的表情）、行板等术语；速度一旦确定就要均匀。
        浪漫主义起常用 rubato（弹性速度），局部伸缩但「有借有还」。均匀的拍加上规律的强弱，才成为拍子：小节第一拍最强，指挥向下挥（下拍），最后一拍向上挥（上拍）。
        中国传统音乐的「板眼」（一板三眼、一板一眼、有板无眼）类似拍子，但不表示强弱，讲究「拍无定值」，不能与西洋节拍画等号。</p>
      <p><b>节拍的层次</b>：拍号所示的拍层之上有大拍、超拍，之下有一层层分拍，每层都是「前强后弱」，叠加后得到总体强弱。
        单拍子二等分，复拍子（6/8、9/8、12/8，俗称三分拍）在拍层三等分、再往下又回到二等分。拍子的强弱与和声密切相关：和弦多在强拍更换，外音分强拍、弱拍两种，强拍会放大协和与不协和。
        流行乐所说的「正拍 / 反拍」是相对的：4/4 拍的一、三拍是正拍，二、四拍和各种后半拍都是反拍。</p>
      <p>此外还有五、七、十一拍等非对称拍子：《小白菜》是 3+2 的五拍子；柴可夫斯基《悲怆》第二乐章、《火星》、《Take Five》、《碟中谍》主题曲也都用五拍子。陈钢《阳光照耀着塔什库尔干》开头是自由拍子（散板，中国写作「サ」），小提琴进入后用 7/8 拍的「前三后四」。</p>
    </Block>


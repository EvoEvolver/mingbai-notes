        <li>排成 <Play notes="B3 E4 G4 C5" arp={0.06}>B–E–G–C</Play>（纯四+大三+纯四）的混合四度排列，或 <Play notes="C3 G3 E4 B4" arp={0.06}>C–G–E–B</Play> 的混合五度排列；</li>

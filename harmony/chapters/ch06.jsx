      <p>声部多于和弦音时要<C id="doubling">重复</C>（Doubling）：优先重复和弦或调式中更自然、稳定、重要的音；不稳定、解决迫切的<strong>倾向音</strong>（活跃音）尽量不重复。古典常用规则：</p>

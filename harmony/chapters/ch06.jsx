    <Block id="resolve" toc="倾向音与音程解决" kicker="6-3 · 倾向音的处理 · 音程的解决" title="七音下行，增扩减缩"
      lead="三全音单独听没有方向；只有解决之后，我们才知道它是哪个调的。">
      <Narrate />
      <p><C id="tendency_resolution">倾向音</C>往往紧张，之前要准备（保持或级进引入），之后解决到稳定的音，而且<strong>在同一声部解决</strong>。七音最规范的解决是同声部下行二度，也可以保持或上行：</p>
      <S ex={X.EX618} tempo={70} caption="谱例 6.18：七音下行（B°7→C、Dm7→G7→C）；七音保持（G7→Bø 的 F 不动，再解决到 Am）；七音上行（FΔ→G7/B→C 的 E→F→G）。" />
      <p>变化音更迫切，按「升号上行、降号下行」在同声部级进或跳进到自然音。属变和弦的例子：
        <Play seq={["G2 B3 F4 D#5", "C3 C4 E4 E5"]} gap={1.1}>G+7 → C</Play>（D♯ 上行到 E，七音 F 下行到 E，主和弦重复三音）、
        <Play seq={["G2 Db4 F4 B4", "C3 C4 E4 C5"]} gap={1.1}>G7♭5 → C</Play>（D♭ 下行到 C）。</p>
      <p>半音进行如果不在同一声部，而在两个声部之间发生，叫<strong>对斜关系</strong>，传统上算不良进行；属变和弦、大调里含 ♭6 级的 iv、♭VI、vii°7、N 都容易出现：</p>
      <S ex={X.EX620} tempo={70} caption="谱例 6.20：F→Fm→C。前两小节 A（女高）到 A♭（男高）跨声部半音，听来别扭；后两小节让 A→A♭ 留在女高音，对斜消失。" />
      <p>这也解释了为什么倾向音不能重复：两个导音都上行、两个七音都下行，必然平行八度。实在要重复，就让一个（多半是高音声部）顺应倾向，另一个另作处理。</p>
      <h4>音程的解决：增扩减缩</h4>
      <p>两个和弦之间，声部间的音程顺着音序 2 向后变（更不协和），张力上升；逆着向前变，张力下降。增、减音程一般按<strong>「增音程扩张，减音程收缩」</strong>解决。
        最典型的是三全音：</p>
      <ul>
        <li><Play seq={["B3 F4", "C4 E4"]} gap={1}>B–F 减五度收缩</Play> 到 C–E（或 <Play seq={["B3 F4", "C4 Eb4"]} gap={1}>C–E♭</Play>）：C 大调或 c 小调；</li>
        <li><Play seq={["B3 F4", "A#3 F#4"]} gap={1}>B–E♯ 增四度扩张</Play> 到 A♯–F♯（或 A–F♯）：F♯ 大调或 f♯ 小调。</li>
      </ul>
      <p>单听 <Play notes="B3 F4">三全音</Play>，人们只觉得不协和，并没有收缩或扩张的倾向——这是三全音的<strong>中立性</strong>。它平分八度，具有两个方向的「双重属功能」，
        这正是三全音替换的根源（5-1）。增六度与小七度也是如此：</p>
      <S ex={X.EX622} tempo={66} caption="谱例 6.22 第二行：A♭+6→G（增六度 A♭–F♯ 向外扩张到 G 八度，低音与女低出现平行五度）；把 F♯ 记成 G♭ 就是 A♭7→D♭（小七度向内收缩）；G♯5♭5/D♭→C；B°7♭3→C。" />
      <p>其他可能还有：三全音的一个音保持、另一个升降半音，进到纯四/五度；或整体平行到另一对三全音。增六/小七度的下方音下行半音时，上方音保持成为大七度、下行半音成为小七度、下行全音则含大六度。</p>
      <p>旋律横向则<strong>「用减不用增」</strong>：主旋律与低音尽量少用增音程（它的扩张感会让旋律继续同向、更失衡），多用减音程，然后顺着收缩感反向级进。
        比较 <Play notes="F4 B4 C5" melodic gap={0.5}>增四度上行 F–B 后继续上行</Play> 与 <Play notes="B4 F4 E4" melodic gap={0.5}>减五度下行 B–F 后反向收缩</Play>，以及和声小调里 <Play notes="Ab4 B4 C5" melodic gap={0.5}>增二度 A♭–B</Play> 与 <Play notes="B4 Ab4 G4" melodic gap={0.5}>减七度 B–A♭</Play>。
        推广：任何不协和的跳进之后，最好反向级进。</p>
      <Callout tone="key" title="和声的「相对论」">
        音、音程、和弦的倾向都相对于调性而言。同一个 E–G 小三度，在 C 大调、a 小调、E♭ 大调、B 大调、f 小调里的音级与倾向完全不同。跳出调性这个参照系，
        一个音程或和弦没有「必然」的解决方向：可以按另一个调解决，引出离调、转调；也可以刻意不解决，成为非功能的色彩和声。
      </Callout>
    </Block>


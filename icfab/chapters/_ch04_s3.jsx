        <Tx>{R`**化合物半导体是不是可以"放松"？**这个产业比硅小得多、也分散得多；GaAs、InP、SiC、GaN 芯片大多比硅处理器/存储器小；而且除 SiC 外它们都是**直接带隙**材料——载流子寿命不由 SRH 复合主导，对痕量污染引入的深能级不那么敏感。于是有人会认为颗粒（良率）和污染问题没那么要紧。这有一定道理，但颗粒与污染控制在化合物半导体工厂里依然非常重要：\figref{4.8} 中的工厂看上去与硅厂无异，只是规模小、洁净度要求低一些（那座 GaAs 厂是 ISO 4，而先进硅厂的关键区是 ISO 1）。

清洗哲学相同：超声/兆声去颗粒，去胶方法同硅，并采用与 RCA 同原理的化学清洗。差别在于要考虑化学液与化合物材料的反应、氧化过程与硅不同，且产品种类（高速数字/模拟电路、光电子、LED、激光器……）多样，清洗方法也更五花八门。两个例子：

◆ **GaAs**（智能手机与基站的射频功放、LED、光电子电路）：要求去除颗粒与污染、去掉表面氧化层并保持表面平整。可用与 SC-1/SC-2 很相似但通常更稀、常在室温下的溶液 [4.17]，留下 $\mathrm{GaO}_x$、$\mathrm{As_2O_3}$、$\mathrm{As_2O_5}$ 混合的自然氧化层；最后用稀 HF、HCl 或 TMAH（四甲基氢氧化铵，一种常作显影液的强碱）冲洗并甩干以去除它 [4.18]。GaAs 表面活性很高，清洗后很快又会重新氧化，所以有研究致力于在外延等关键步骤之前**原位**去除氧化层 [4.19]。

◆ **SiC**（宽禁带，适合功率 MOSFET、IGBT、PIN 二极管）：与硅一样是间接带隙，硅工艺中的一切颗粒与污染问题它都有；但芯片较小，工厂较简单、管控也较宽松。SiC 的清洗与硅非常相似：去胶可用包括 $\mathrm{H_2SO_4/H_2O_2}$ 在内的各种方法，RCA 清洗可以直接使用 [4.20]。唯一真正的差别在最后剥自然氧化层：硅片 HF 浸泡后得到氢钝化表面；SiC 表面化学不同，HF 处理后表面亲水、以 O 或 OH 终止 [4.21]，因此有时改用氢等离子体去除氧化层 [4.22]。`}</Tx>
